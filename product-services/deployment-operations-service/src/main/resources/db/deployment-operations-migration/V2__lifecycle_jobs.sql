CREATE TABLE deployment_lifecycle_job (
    operation_id VARCHAR(128) PRIMARY KEY,
    grant_id VARCHAR(128) NOT NULL UNIQUE,
    request_digest VARCHAR(64) NOT NULL,
    request_json TEXT NOT NULL,
    customer_id VARCHAR(128) NOT NULL,
    tenant_id VARCHAR(128) NOT NULL,
    deployment_id VARCHAR(128) NOT NULL,
    target_profile_id VARCHAR(128) NOT NULL,
    state VARCHAR(24) NOT NULL,
    step_index INTEGER NOT NULL,
    irreversible BOOLEAN NOT NULL DEFAULT FALSE,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    code VARCHAR(128) NOT NULL,
    due_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_token VARCHAR(64),
    lease_until TIMESTAMP WITH TIME ZONE,
    notice_emitted BOOLEAN NOT NULL DEFAULT FALSE,
    due_emitted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX deployment_lifecycle_due_idx ON deployment_lifecycle_job (state, due_at);
CREATE TABLE deployment_lifecycle_target (
    deployment_id VARCHAR(128) NOT NULL,
    target_profile_id VARCHAR(128) NOT NULL,
    customer_id VARCHAR(128) NOT NULL,
    tenant_id VARCHAR(128) NOT NULL,
    operation_id VARCHAR(128) REFERENCES deployment_lifecycle_job(operation_id),
    PRIMARY KEY (deployment_id, target_profile_id)
);
CREATE TABLE deployment_lifecycle_command (
    command_id VARCHAR(128) PRIMARY KEY,
    operation_id VARCHAR(128) NOT NULL REFERENCES deployment_lifecycle_job(operation_id),
    phase VARCHAR(32) NOT NULL,
    command_json TEXT NOT NULL,
    delivery VARCHAR(16) NOT NULL CHECK (delivery IN ('READY', 'SENT')),
    observation_pending BOOLEAN NOT NULL DEFAULT FALSE,
    receipt_json TEXT,
    UNIQUE (operation_id, phase)
);
CREATE TABLE deployment_lifecycle_event (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    operation_id VARCHAR(128) NOT NULL REFERENCES deployment_lifecycle_job(operation_id),
    event_type VARCHAR(64) NOT NULL,
    state VARCHAR(24) NOT NULL,
    phase VARCHAR(32),
    code VARCHAR(128) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivery VARCHAR(16) NOT NULL CHECK (delivery IN ('DISABLED', 'PENDING', 'DELIVERED', 'EXHAUSTED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_token VARCHAR(64),
    lease_until TIMESTAMP WITH TIME ZONE
);
CREATE INDEX deployment_lifecycle_event_job_idx ON deployment_lifecycle_event (operation_id, sequence_id);
CREATE INDEX deployment_lifecycle_outbox_idx ON deployment_lifecycle_event (delivery, next_attempt_at);
