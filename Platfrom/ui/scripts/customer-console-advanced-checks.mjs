import assert from 'node:assert/strict'

const settle = page => page.evaluate(() => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))))
const noCommands = async page => assert.deepEqual((await page.evaluate(() => window.previewRequests))
  .filter(request => request.method !== 'GET' && request.path !== '/api/platform/preferences'), [], 'Changing detail depth must not dispatch a command')

export async function verifyAdvancedViews({ browser, base, output, report }) {
  for (const product of ['dealership', 'shopify']) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const page = await context.newPage()
    page.on('pageerror', error => report.errors.push(error.message))
    const appName = product === 'shopify' ? 'Storefront AI workspace' : 'Northfield AI'
    await page.goto(`${base}/?product=${product}&state=draft#/ai-workspaces?resourceKind=app&resourceId=preview-app`)
    const inspector = page.getByRole('complementary', { name: `${appName} details` })
    await inspector.waitFor()
    for (const name of ['Overview', 'Configuration', 'Advanced']) {
      await inspector.getByRole('tab', { name, exact: true }).click()
      await inspector.getByRole('alert').filter({ hasText: 'Custom domain needs DNS verification.' }).waitFor()
    }
    await inspector.getByText('Installation ID', { exact: true }).waitFor()
    await page.reload()
    await inspector.getByRole('tab', { name: 'Advanced', exact: true, selected: true }).waitFor()
    await inspector.getByRole('button', { name: 'Open advanced settings', exact: true }).click()
    const depth = page.getByRole('tablist', { name: 'Configuration depth', exact: true })
    await depth.getByRole('tab', { name: 'Advanced', exact: true, selected: true }).waitFor()
    await page.getByRole('button', { name: 'Delete draft app', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Delete draft app', exact: true }).click()
    await page.getByRole('dialog', { name: 'Delete draft app?', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await depth.getByRole('tab', { name: 'Configuration', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Delete draft app', exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Edit app', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Edit AI App', exact: true })
    const input = dialog.getByRole('textbox', { name: 'Workspace name', exact: true })
    await input.fill('Same customer draft, both views')
    const modalDepth = dialog.getByRole('tablist', { name: 'App configuration depth', exact: true })
    for (const name of ['Advanced', 'Configuration', 'Advanced']) {
      await modalDepth.getByRole('tab', { name, exact: true }).click()
      assert.equal(await input.inputValue(), 'Same customer draft, both views')
      assert.equal(await dialog.getByRole('button', { name: 'Save draft', exact: true }).isDisabled(), true, 'Advanced must not bypass reviewed-profile authorization')
      await dialog.getByRole('alert').filter({ hasText: 'current reviewed offer' }).waitFor()
      await dialog.getByRole('alert').filter({ hasText: 'Custom domain needs DNS verification.' }).waitFor()
    }
    await page.emulateMedia({ colorScheme: 'dark' })
    await settle(page)
    assert.equal(await input.inputValue(), 'Same customer draft, both views')
    await page.screenshot({ path: `${output}/advanced-${product}-same-session-draft-dark.png` })
    await noCommands(page)
    const session = await page.evaluate(() => fetch('/api/platform/auth/session').then(response => response.json()))
    assert.equal(session.role, 'CUSTOMER_ADMIN')
    assert.equal(session.customerId, 'preview-customer')
    assert.equal(session.authenticationMode, 'SESSION')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Close configuration', exact: true }).click()
    await page.getByRole('button', { name: 'Close panel', exact: true }).click()
    await page.evaluate(() => localStorage.setItem('loomai-customer-detail:app', 'PLATFORM_OPERATOR'))
    await page.reload()
    await inspector.getByRole('tab', { name: 'Overview', exact: true, selected: true }).waitFor()
    await noCommands(page)
    report.checks.push({ scenario: `advanced-${product}-same-account-retained-draft-no-authority-escalation-no-replay`, status: 'PASS' })
    await context.close()
  }

  const context = await browser.newContext({ viewport: { width: 1280, height: 800 } })
  const page = await context.newPage()
  page.on('pageerror', error => report.errors.push(error.message))
  const target = 'deploymentId=preview-deployment&releaseId=preview-production-release'
  await page.goto(`${base}/?editable=1#/document-knowledge?${target}&sourceId=preview-policy&editor=configuration`)
  await page.getByRole('heading', { name: 'Document Knowledge', exact: true }).waitFor()
  const proof = page.getByRole('textbox', { name: 'Proof query', exact: true })
  const secret = page.getByRole('textbox', { name: 'Secret key', exact: true })
  await proof.fill('Keep this unsaved query across view switches')
  await secret.fill('fictional-unsaved-secret')
  const depth = page.getByRole('tablist', { name: 'Configuration depth', exact: true })
  assert.equal(await page.getByRole('heading', { name: 'Runtime evidence retention', exact: true }).count(), 0)
  for (const name of ['Advanced', 'Configuration', 'Advanced']) {
    await depth.getByRole('tab', { name, exact: true }).click()
    assert.equal(await proof.inputValue(), 'Keep this unsaved query across view switches')
    assert.equal(await secret.inputValue(), 'fictional-unsaved-secret')
    assert.equal(await secret.getAttribute('type'), 'password')
    assert.equal(await page.getByRole('button', { name: 'Save binding', exact: true }).isDisabled(), true)
  }
  await page.getByRole('heading', { name: 'Runtime evidence retention', exact: true }).waitFor()
  assert(!(await page.evaluate(() => JSON.stringify(localStorage))).includes('fictional-unsaved-secret'))
  assert(!page.url().includes('fictional-unsaved-secret'))
  await settle(page)
  await page.screenshot({ path: `${output}/advanced-document-retained-form.png` })
  await noCommands(page)
  await context.close()

  const connection = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  connection.on('pageerror', error => report.errors.push(error.message))
  await connection.goto(`${base}/#/integrations?${target}&editor=configuration&editorSection=advanced`)
  await connection.getByRole('heading', { name: 'Connection and authority', exact: true }).waitFor()
  const connectionDepth = connection.getByRole('tablist', { name: 'Configuration depth', exact: true })
  await connectionDepth.getByRole('tab', { name: 'Configuration', exact: true }).click()
  assert.equal(await connection.getByRole('heading', { name: 'Connection and authority', exact: true }).count(), 0)
  await connection.getByRole('heading', { name: 'Live data sources', exact: true }).waitFor()
  await connectionDepth.getByRole('tab', { name: 'Advanced', exact: true }).click()
  await connection.getByRole('heading', { name: 'Connection and authority', exact: true }).waitFor()
  await noCommands(connection)
  report.checks.push({ scenario: 'advanced-documents-connections-retained-inputs-write-only-secrets-scoped-command-denial', status: 'PASS' })
  await connection.close()
}
