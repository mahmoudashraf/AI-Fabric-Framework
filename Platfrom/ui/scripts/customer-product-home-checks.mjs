import assert from 'node:assert/strict'

const noCommands = async page => assert.deepEqual((await page.evaluate(() => window.previewRequests)).filter(request => request.method !== 'GET'), [])
const settle = page => page.evaluate(() => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))))

export async function verifyProductHome({ browser, base, output, report }) {
  for (const product of ['dealership', 'shopify']) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const page = await context.newPage()
    page.on('pageerror', error => report.errors.push(error.message))
    await page.goto(`${base}/?product=${product}&state=history#/home`)
    const name = product === 'shopify' ? 'Shopify AI' : 'Dealership AI'
    const productCard = page.getByRole('region', { name: `${name} product`, exact: true })
    await productCard.getByRole('heading', { name, exact: true }).waitFor()
    await page.getByRole('region', { name: 'Engage Apps product', exact: true }).waitFor()
    await page.getByRole('alert').filter({ hasText: 'Custom domain needs DNS verification.' }).waitFor()
    assert.equal(await page.getByText('Old draft binding missing', { exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Old disabled app', exact: true }).count(), 0)
    assert.equal(await page.getByRole('link', { name: 'Create deployment', exact: true }).count(), 0)
    await page.screenshot({ path: `${output}/m1-${product}-home-light.png`, fullPage: true })
    await page.getByRole('combobox', { name: 'Customer color theme', exact: true }).click()
    await page.getByRole('option', { name: 'Dark', exact: true }).click()
    await settle(page)
    await page.screenshot({ path: `${output}/m1-${product}-home-dark.png`, fullPage: true })
    await page.getByRole('button', { name: /^Other deployments and app drafts/ }).click()
    await page.getByRole('button', { name: 'Unused configuration', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Old disabled app', exact: true }).click()
    await page.getByRole('complementary', { name: 'Old disabled app details', exact: true }).getByRole('alert').filter({ hasText: 'Old draft binding missing' }).waitFor()
    await page.getByRole('button', { name: 'Close resource details', exact: true }).click()
    await page.getByRole('complementary', { name: 'Old disabled app details', exact: true }).waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 390, height: 844 })
    await settle(page)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
    await page.screenshot({ path: `${output}/m1-${product}-home-mobile.png`, fullPage: true })
    await noCommands(page)
    report.checks.push({ scenario: `m1-${product}-metadata-product-entry-active-warnings-inactive-history-both-themes-mobile`, status: 'PASS' })
    await context.close()
  }

  const page = await browser.newPage()
  page.on('pageerror', error => report.errors.push(error.message))
  await page.goto(`${base}/?state=multiple-offers#/home`)
  const product = page.getByRole('region', { name: 'Dealership AI product', exact: true })
  await product.getByRole('heading', { name: 'Dealership AI', exact: true }).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Dealership AI', exact: true }).count(), 1)
  await product.getByRole('button', { name: 'Start another setup', exact: true }).click()
  const setup = product.getByRole('link', { name: 'Open setup', exact: true })
  assert.equal(await setup.count(), 2)
  assert.equal(new URL(await setup.nth(1).getAttribute('href'), 'https://fixture.test').hash.includes('offerId=preview-offer-two'), true)
  await noCommands(page)

  await page.goto(`${base}/?state=first#/home`)
  await page.getByRole('link', { name: 'Set up Dealership AI', exact: true }).waitFor()
  assert.equal(await page.getByRole('navigation', { name: 'Customer navigation' }).getByRole('link').count(), 4)
  await noCommands(page)
  await page.goto(`${base}/?state=revoked#/home`)
  await page.getByRole('alert').filter({ hasText: 'template access is no longer active' }).waitFor()
  assert.equal(await page.getByRole('link', { name: 'Open setup', exact: true }).count(), 0)
  assert.equal(await page.getByRole('link', { name: 'Set up Dealership AI', exact: true }).count(), 0)
  await noCommands(page)
  await page.goto(`${base}/?state=catalogue-error#/home`)
  await page.getByRole('alert').filter({ hasText: 'unavailable in the current offline scenario' }).waitFor()
  assert.equal(await page.getByText('No deployment template is currently available.', { exact: false }).count(), 0, 'A failed catalogue must not be shown as empty success')
  await noCommands(page)
  report.checks.push({ scenario: 'm1-explicit-offer-selection-first-use-revocation-and-read-error', status: 'PASS' })
  await page.close()
}
