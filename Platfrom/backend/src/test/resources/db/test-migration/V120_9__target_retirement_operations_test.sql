CREATE TABLE platform_target_retirement_gates (
    id VARCHAR(64) PRIMARY KEY,
    deployment_id VARCHAR(64) NOT NULL,
    target_profile_id VARCHAR(64) NOT NULL,
    state VARCHAR(64) NOT NULL,
    epoch BIGINT NOT NULL DEFAULT 0,
    operation_id VARCHAR(64),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    row_version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_target_retirement_gate UNIQUE (deployment_id, target_profile_id),
    CONSTRAINT ck_target_retirement_gate_state CHECK (state IN ('AVAILABLE', 'RETIRING', 'RETIRED'))
);

CREATE TABLE platform_target_retirement_operations (
    id VARCHAR(64) PRIMARY KEY,
    customer_id VARCHAR(64) NOT NULL,
    deployment_id VARCHAR(64) NOT NULL,
    target_profile_id VARCHAR(64) NOT NULL,
    operation_key VARCHAR(128) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    requested_by_actor_id VARCHAR(255) NOT NULL,
    requested_by_role VARCHAR(64) NOT NULL,
    request_json TEXT NOT NULL,
    snapshot_json TEXT NOT NULL,
    result_json TEXT NOT NULL,
    state VARCHAR(64) NOT NULL,
    step VARCHAR(64) NOT NULL,
    fence_epoch BIGINT NOT NULL DEFAULT 0,
    drain_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    attempt INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP WITH TIME ZONE,
    error_code VARCHAR(64),
    worker_token VARCHAR(64),
    lease_expires_at TIMESTAMP WITH TIME ZONE,
    in_flight_effect VARCHAR(255),
    destructive_started BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    step_started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    row_version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_target_retirement_operation UNIQUE (deployment_id, target_profile_id, operation_key),
    CONSTRAINT ck_target_retirement_attempt CHECK (attempt >= 0 AND attempt <= 8),
    CONSTRAINT ck_target_retirement_state CHECK (state IN ('PLANNED', 'QUEUED', 'RUNNING', 'WAITING', 'RETAINED', 'BLOCKED',
        'RETRYABLE_FAILURE', 'CANCEL_REQUESTED', 'CANCELLED', 'COMPLETE')),
    CONSTRAINT ck_target_retirement_step CHECK (step IN ('DRAIN', 'AUTHORITY', 'INDEX', 'RESOURCES', 'DEPENDENCIES', 'VERIFY', 'CANCEL_DRAIN'))
);
CREATE INDEX ix_target_retirement_reconcile ON platform_target_retirement_operations (state, next_retry_at, updated_at);
