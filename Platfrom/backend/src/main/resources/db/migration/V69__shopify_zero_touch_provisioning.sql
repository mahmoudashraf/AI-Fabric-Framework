create table if not exists shopify_companion_package_profiles (
    id varchar(64) primary key,
    profile_key varchar(64) not null unique,
    package_key varchar(64) not null,
    tier_key varchar(64) not null,
    runtime_profile_key varchar(64) not null,
    vector_profile_key varchar(64) not null,
    display_name varchar(255) not null,
    description text,
    cost_posture varchar(64) not null,
    template_plugin_id varchar(128) not null,
    template_plugin_version varchar(64),
    deployment_template_id varchar(128) not null,
    inference_plugin_id varchar(128) not null,
    vector_strategy varchar(64) not null,
    vector_provisioning_mode varchar(64) not null,
    vector_storage_posture varchar(64) not null,
    verification_pack_id varchar(128) not null,
    status varchar(64) not null,
    details_json text not null default '{}',
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create index if not exists idx_shopify_companion_package_profiles_package
    on shopify_companion_package_profiles(package_key, tier_key, status);

