create table if not exists shopify_store_provisioning_jobs (
    id varchar(64) primary key,
    shop_domain varchar(255) not null,
    store_connection_id varchar(64),
    job_type varchar(64) not null,
    status varchar(64) not null,
    phase varchar(64) not null,
    requested_package_key varchar(64),
    requested_tier_key varchar(64),
    requested_runtime_profile_key varchar(64),
    requested_vector_profile_key varchar(64),
    previous_package_key varchar(64),
    previous_runtime_profile_key varchar(64),
    previous_vector_profile_key varchar(64),
    requested_template_plugin_id varchar(128),
    requested_template_plugin_version varchar(64),
    requested_plugin_ids_json text not null default '[]',
    profile_change_strategy varchar(64),
    vector_reindex_required boolean not null default false,
    install_intent_id varchar(128),
    attempt_count integer not null default 0,
    max_attempts integer not null default 5,
    lease_owner varchar(128),
    lease_expires_at timestamp with time zone,
    last_error_code varchar(128),
    last_error_message text,
    bootstrap_deployment_id varchar(128),
    verification_run_id varchar(128),
    next_action text,
    summary_message text,
    ready_at timestamp with time zone,
    failed_at timestamp with time zone,
    cancelled_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint fk_shopify_store_provisioning_jobs_store
        foreign key (store_connection_id) references shopify_store_connections(id)
);

create index if not exists idx_shopify_store_provisioning_jobs_shop_created
    on shopify_store_provisioning_jobs(shop_domain, created_at desc);

create index if not exists idx_shopify_store_provisioning_jobs_status_phase
    on shopify_store_provisioning_jobs(status, phase, created_at asc);

create index if not exists idx_shopify_store_provisioning_jobs_lease
    on shopify_store_provisioning_jobs(status, lease_expires_at, created_at asc);
