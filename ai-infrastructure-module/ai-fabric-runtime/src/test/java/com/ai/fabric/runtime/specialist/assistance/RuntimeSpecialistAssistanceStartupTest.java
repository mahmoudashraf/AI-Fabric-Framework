@SpringBootTest(classes = AIFabricRuntimeApplication.class,
    args = "--spring.config.import=classpath:test-runtime-entity-config.yml",
    properties = {
        "OPENAI_ENABLED=true",
        "OPENAI_API_KEY=startup-test-not-a-real-key",
        "AI_VECTOR_DB_TYPE=memory",
        "ACTIONS_CONNECTOR_API_KEY=startup-test-not-a-real-key",
        "spring.datasource.url=jdbc:h2:mem:specialist-assistance-startup;DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE",
        "spring.jpa.hibernate.ddl-auto=create-drop",
        "AI_FABRIC_RUNTIME_AUTH_INGRESS_MODE=VERIFIED_CONTEXT_REQUIRED",
        "AI_FABRIC_RUNTIME_TRUSTED_BACKEND_API_KEY=startup-trusted-backend-secret",
        "AI_FABRIC_RUNTIME_PRIVATE_ASSERTION_SIGNING_KEY=startup-private-signing-secret",
        "AI_FABRIC_RUNTIME_AUTH_ACCEPTED_ISSUERS=platform-poc:SESSION,platform-poc:API_KEY,platform-poc:SYSTEM",
        "AI_FABRIC_RUNTIME_AUTH_ACCEPTED_AUDIENCES=dep-runtime",
        "AI_EXECUTION_MANIFESTS_ENABLED=true",
        "AI_EXECUTION_SPECIALIST_CHAINS_ENABLED=true",
        "AI_EXECUTION_SPECIALIST_CHAINS_DURABLE_ENABLED=true",
        "AI_SPECIALIST_CHAIN_ENCRYPTION_SECRET=startup-chain-encryption-secret-at-least-32-characters",
        "AI_SPECIALIST_CHAIN_FINGERPRINT_SECRET=startup-chain-fingerprint-secret-at-least-32-characters"
    })
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
class RuntimeSpecialistAssistanceStartupTest {
    // Generated by SpecialistAssistanceCompiler.compileBehavior using the reviewed
    // ai-support-workspace manifest, CONVERSATIONAL defaults and document-only authority.
    private static final JsonNode FIXTURE = fixture();
    private static final AtomicInteger PROVIDER_REQUESTS = new AtomicInteger();
    private static final HttpServer PROVIDER_TRIPWIRE = tripwire();

    @Autowired private SpecialistAssistanceBundle bundle;
    @Autowired private SpecialistResourceBundle resources;
    @Autowired private SpecialistRegistry specialists;
    @Autowired private SpecialistManifestRuntimeStatus specialistStatus;
    @Autowired private SpecialistChainRegistry chains;
    @Autowired private SpecialistChainGateway chainGateway;
    @Autowired private SpecialistChainExecutionRepository chainRepository;
    @Autowired private SpecialistChainManifestRuntimeStatus chainStatus;
    @Autowired private AIActionRegistry actions;
    @Autowired private SpecialistAssistanceStatusService status;
    @Autowired private SpecialistAssistanceHealthIndicator health;

    @DynamicPropertySource
    static void publishedBundle(DynamicPropertyRegistry properties) throws Exception {
        byte[] bytes = new ObjectMapper().writeValueAsBytes(FIXTURE.path("compiled"));
        assertThat("sha256:" + HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)))
            .isEqualTo(FIXTURE.path("contentHash").asText());
        properties.add("LOOMAI_SPECIALIST_ASSISTANCE_BUNDLE_BASE64", () -> Base64.getEncoder().encodeToString(bytes));
        properties.add("LOOMAI_SPECIALIST_ASSISTANCE_BUNDLE_HASH", () -> FIXTURE.path("contentHash").asText());
        String baseUrl = "http://127.0.0.1:" + PROVIDER_TRIPWIRE.getAddress().getPort();
        properties.add("OPENAI_BASE_URL", () -> baseUrl + "/v1");
        properties.add("ai.providers.openai.base-url", () -> baseUrl + "/v1");
        properties.add("ACTIONS_CONNECTOR_BASE_URL", () -> baseUrl);
    }

    @Test
    void loadsCompilerGeneratedOfficialResourcesAndDurableChainThroughSpring() throws IOException {
        assertThat(bundle.enabled()).isTrue();
        assertThat(bundle.content()).isEqualTo(FIXTURE.path("compiled"));
        assertThat(bundle.contentHash()).isEqualTo(FIXTURE.path("contentHash").asText());
        assertThat(resources.diagnostics()).isEmpty();
        assertThat(resources.schemas()).hasSizeGreaterThanOrEqualTo(4);
        assertThat(resources.promptProfiles()).hasSizeGreaterThanOrEqualTo(3);
        assertThat(specialistStatus.enabled()).isTrue();
        assertThat(specialistStatus.ready()).isTrue();
        assertThat(specialistStatus.diagnostics()).isEmpty();

        Path root = Path.of(System.getProperty("java.io.tmpdir"), "loomai-specialist-assistance",
            bundle.contentHash().substring("sha256:".length()));
        JsonNode generated = bundle.content().path("resources");
        for (int i = 0; i < generated.size(); i++) {
            JsonNode resource = generated.get(i);
            assertThat(new ObjectMapper().readTree(Files.readAllBytes(root.resolve("resource-" + i + ".json"))))
                .isEqualTo(resource);
            if ("Specialist".equals(resource.path("kind").asText())) {
                assertThat(specialists.find(SpecialistId.parse(resource.at("/metadata/name").asText() + "@1")))
                    .as("official specialist %s", resource.at("/metadata/name").asText()).isPresent();
            }
        }
        assertThat(chains.find(SpecialistChainId.parse("assist-chain-setup-and-support@1"))).isPresent();
        assertThat(chainGateway).isNotNull();
        assertThat(chainRepository).isInstanceOf(JdbcSpecialistChainExecutionRepository.class);
        assertThat(chainStatus.manifestLoadingEnabled()).isTrue();
        assertThat(chainStatus.chainExecutionEnabled()).isTrue();
        assertThat(chainStatus.ready()).isTrue();
        assertThat(chainStatus.discoveredManifestCount()).isEqualTo(1);
        assertThat(chainStatus.manifestDefinedCount()).isEqualTo(1);
        assertThat(chainStatus.inactiveManifestCount()).isZero();
        assertThat(chainStatus.diagnostics()).isEmpty();
        assertThat(PROVIDER_REQUESTS.get()).as("no provider or connector call during startup").isZero();
    }

    @Test
    void registersNativeReadActionAndReportsExactBundleReadiness() {
        var metadata = actions.findMetadata("consult_specialist").orElseThrow();
        assertThat(actions.findHandler("consult_specialist")).isPresent();
        assertThat(metadata.getAccessMode()).isEqualTo(ActionAccessMode.READ);
        assertThat(metadata.getSideEffectLevel()).isEqualTo(ActionSideEffectLevel.NONE);
        assertThat(metadata.isConfirmationRequired()).isFalse();
        assertThat(metadata.isReadActionResolutionEligible()).isTrue();
        assertThat(metadata.getRequiredParameters()).containsExactlyInAnyOrder("capabilityId", "question");
        assertThat(metadata.getParameterSchemas().get("capabilityId").getAllowedValues())
            .containsExactlyInAnyOrder("product-setup", "service-policy", "setup-and-support");
        assertThat(status.status()).containsEntry("enabled", true).containsEntry("ready", true)
            .containsEntry("contractVersion", SpecialistAssistanceBundle.CONTRACT)
            .containsEntry("contentHash", bundle.contentHash())
            .containsEntry("invocations", FIXTURE.path("compiled").path("invocations"));
        assertThat(health.health().getStatus().getCode()).isEqualTo("UP");
        assertThat(health.health().getDetails()).containsEntry("enabled", true)
            .containsEntry("contentHash", bundle.contentHash());
        assertThat(PROVIDER_REQUESTS.get()).as("registration and readiness must not invoke AI").isZero();
    }

    @AfterAll
    static void noExternalWorkWasNeeded() {
        PROVIDER_TRIPWIRE.stop(0);
        assertThat(PROVIDER_REQUESTS.get()).as("startup qualification performs no model calls").isZero();
    }

    private static JsonNode fixture() {
        try (var input = new ClassPathResource("specialist-assistance/compiler-generated-support-startup.json").getInputStream()) {
            return new ObjectMapper().readTree(input);
        } catch (IOException failure) {
            throw new ExceptionInInitializerError(failure);
        }
    }

    private static HttpServer tripwire() {
        try {
            HttpServer server = HttpServer.create(new InetSocketAddress(InetAddress.getByName("127.0.0.1"), 0), 0);
            server.createContext("/", exchange -> {
                PROVIDER_REQUESTS.incrementAndGet();
                exchange.sendResponseHeaders(503, -1);
                exchange.close();
            });
            server.start();
            return server;
        } catch (IOException failure) {
            throw new ExceptionInInitializerError(failure);
        }
    }
}
